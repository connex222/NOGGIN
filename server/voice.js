'use strict';
// Builds public/voice/voice-manifest.json from the recordings in public/voice/,
// and writes VOICE-SCRIPT.md (the recording script) from public/shared/voice-lines.json.
// Usage: node server/voice.js   (the server also builds the manifest live on request)
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.join(__dirname, '..');
const VOICE = path.join(ROOT, 'public', 'voice');
const {lines, about} = JSON.parse(fs.readFileSync(path.join(ROOT, 'public', 'shared', 'voice-lines.json'), 'utf8'));
const ids = new Set(lines.map(l => l.id));
const AUDIO = /^([a-z0-9-]+?)(?:-(\d+))?\.(mp3|m4a|ogg|wav)$/;
function scan(dir = VOICE) {
  const takes = {}, unknown = [];
  if (!fs.existsSync(dir)) return {takes, unknown};
  for (const file of fs.readdirSync(dir).sort()) {
    const m = AUDIO.exec(file); if (!m) continue;
    // "game-quick-draw.mp3" must not be read as take "draw" of "game-quick": match the longest known id.
    const stem = file.replace(/\.(mp3|m4a|ogg|wav)$/, '');
    const id = ids.has(stem) ? stem : (ids.has(stem.replace(/-\d+$/, '')) ? stem.replace(/-\d+$/, '') : null);
    if (!id) {unknown.push(file); continue;}
    (takes[id] ||= []).push(file);
  }
  return {takes, unknown};
}
function build() {
  fs.mkdirSync(VOICE, {recursive: true});
  const {takes, unknown} = scan();
  const manifest = {description: 'Generated by tools/make-voice-manifest.js. Do not edit by hand.', lines: takes};
  fs.writeFileSync(path.join(VOICE, 'voice-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  const done = Object.keys(takes).length;
  const script = ['# NOGGIN host voice — recording script', '', about, '',
    `**Recorded so far: ${done} of ${lines.length} lines.** Tick them off as you go.`, '',
    'Tips: record on your phone in a quiet room, about 20 cm from your mouth. Big energy — it\'s a game show. Leave half a second of silence at each end. Any of the suggested wordings is fine, or say it your own way.', '',
    '| ✓ | File name | When it plays | Suggested lines (one per take) |', '|---|---|---|---|',
    ...lines.map(l => `| ${takes[l.id] ? '✅' : '⬜'} | \`${l.id}.mp3\` | ${l.when} | ${l.say.map(x => `“${x}”`).join('<br>')} |`), ''];
  fs.writeFileSync(path.join(ROOT, 'VOICE-SCRIPT.md'), script.join('\n'));
  return {done, total: lines.length, unknown};
}
if (require.main === module) {
  const r = build();
  console.log(`Voice: ${r.done}/${r.total} lines recorded.${r.unknown.length ? ' Ignored (unknown names): ' + r.unknown.join(', ') : ''}`);
}
module.exports = {build, scan};
